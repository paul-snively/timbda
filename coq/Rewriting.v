(* ---------- Fig. 8 (lines 412-417): substitution and promotion ----------
   `subst`: x = the body-position index of a *valued* slot; S = the binder-free
   CtxS fragment (Syntax.v header: with bvs(S) = empty the paper side condition
   x not in bvs(S) is automatic).  The heap entry v lives at the slot's own entry
   position, the occurrence S[x] at the body position: `slotValueFromBody` is the
   reindexing between the two, and the block wrapper is common to both sides. *)
| RewSubst : forall slots (p : nat) (v : Val) (k : CtxS),
    slot_value_at slots p = Some v ->
    Rew (Block slots (fillS k (Ret (VVar (slot_body_idx (length slots) p)))))
        (Block slots (fillS k (Ret (slotValueFromBody (length slots) p v))))
    (* audit: Subst | fig:8 | tier:1 | existsX{hp, x v}. S[x] -> existsX{hp, x v}. S[v]
       if x not in bvs(S); binder-free-S kernel restriction + CtxS closure recorded *)
| RewGc1 : forall slots (p : nat) (body : Expr),
    slot_value_at slots p <> @None Val ->
    slot_unused (length slots) p slots body = true ->
    Rew (Block slots body)
        (Block (dropSlot (length slots) p slots)
               (shrinkE (slot_body_idx (length slots) p) body))
    (* audit: Gc1 | fig:8 | tier:1 | existsX,Y{hp}. e -> existsX{hp_Y}. e for Y a single
       unused value binding; the paper's SCC form (recursive heaps) is the admitted
       Tier-2 row `Gc-Rec` (VERSE-RULES 3.2), and the non-recursive M0 restriction is
