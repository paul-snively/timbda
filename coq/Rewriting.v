        (Block [(t, @None Val)] (Seq (Unify (Ret (VVar 0)) (liftE 1 0 e)) b))
    (* audit: BetaL | fig:11 | tier:1 | (λx.b)[e] -> block{∃x{}. x = e; block{b}} *)
| RewBetaT : forall (vs : list Val) (e : Expr),
    vs <> nil ->
    Rew (App (Ret (VTup vs)) e)
        (Block [(@TAny, @None Val)]
               (Seq (Unify (Ret (VVar 0)) (liftE 1 0 e)) (choice_list (beta_t_cands 0 vs))))
    (* audit: BetaT | fig:11 | tier:1 | ⟨v0,..,vn⟩[e] ->
       block{∃x{}. x = e; ((∃{}. x = 0; v0) .. (∃{}. x = n; vn))}; narrowing;
       the paper's `∃{}` is an empty slot list, hence index-neutral *)
| RewBetaT0 : forall (e : Expr),
    Rew (App (Ret (VTup (@nil Val))) e) Fail
    (* audit: BetaT0 | fig:11 | tier:1 | base case of beta-t: ⟨⟩[e] -> fail (line 475);
       KERNEL-SIDE named rule extracted from that note *)

(* ---------- Fig. 12 (lines 479-491): structural and normalisation ---------- *)
| RewSeq : forall (v : Val) (e : Expr),
    Rew (Seq (Ret v) e) e
    (* audit: Seq | fig:12 | tier:1 | v ; e -> e *)
| RewNorm1 : forall (v : Val) (e1 e2 : Expr),
