| RewLamAlpha : forall (t : Ty) (e : Expr),
    Rew (Ret (VLam t e)) (Ret (VLam t e))
    (* audit: LamAlpha | fig:12 | tier:1 | λx.e <-> λy.e[x/y]; same treatment as HpAlpha *)
| RewFloat : forall (sx sy : list (Ty * option Val)) (body : Expr),
