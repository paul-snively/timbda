    (* audit: IterFail | fig:13 | tier:1 | iter(ic){B[C[fail]]}{e} -> e *)
| RewIterChoice : forall (ic : IterComb) (slots : list (Ty * option Val)) (k : CtxC)
    (e1 e2 e : Expr),
    leftChoiceFreeC k = true ->
