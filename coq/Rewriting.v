| RewDotDot : forall a b : Z,
    Rew (prim_app PDotDot [Ret (VInt a); Ret (VInt b)])
        (Ret (VTup (map VInt (seq_z a b))))
    (* audit: DotDot | fig:10 | tier:1 | dotdot[ki1, ki2] -> ki1 (ki1+1) .. ki2;
       kernel form: the range literal is materialised as a tuple of ints *)
| RewPrim : forall (p : Prim) (vs : list Val) (v : Val),
    prim_total p vs = PRes v ->
    Rew (prim_app p (map Ret vs)) (Ret v)
    (* audit: PrimSchema | fig:10 | tier:1 | op[gv ..] -> result of the total primop
