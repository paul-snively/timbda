       schema (gt2/isInt2 are the named instances); SCHEMA record *)

(* ---------- Fig. 11 (lines 468-469): beta reduction ----------
   beta-l: the paper's side condition `x ∉ fvs(e)` (line 468) is discharged by the
   representation: `e` is lifted past the new slot, and `b` keeps its indices because
   the block's slot 0 replaces the lambda's binder at the same index.  The kernel's
   slot is *declared* (`None`) and the binding is written literally as the unification
   `x = e` in the body, exactly as the paper has it; `subst`/promote turn it into a
