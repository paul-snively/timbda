| RewPromoteL : forall slots (p : nat) (k : CtxC) (v : Val),
    slot_value_at slots p = @None Val ->
    promote_ok (length slots) v = true ->
    promote_hp_ok slots p = true ->
    Rew (Block slots (fillC k (Unify (Ret (VVar (slot_body_idx (length slots) p))) (Ret v))))
        (Block (fillSlot p (bodyToSlotV (length slots) p v) slots) (fillC k (Ret v)))
    (* audit: PromoteL | fig:8 | tier:2 | existsX,x{hp}. C[x = v] ->
       existsX,x{hp[v/x], x v}. C[v]; Tier 2: the constructor carries the successful
       promotion (fill slot + discharge unification to `Ret v`, matching eqk1's
       "unification returns its value"), while `hp[v/x]` is restricted to the identity
