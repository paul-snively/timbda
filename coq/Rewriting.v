(* Timbda-0 kernel: the Tier-1 rewrite rules.

   Transcription source: docs/VERSE-RULES.md §§ 2-3.4 (paper Figs. 8, 9, 10, 11, 12,
   13).  Every constructor below is tagged with an audit comment

     (* audit: <RuleName> | fig:<n> | tier:<1|2> | <paper form> *)

   and docs/RULES-AUDIT.md (generated by tools/rules-audit.py, M1) diffs these tags
   against the `TimbdaRule` records in dialect/Timbda.td and the rule tables of
   VERSE-RULES.md.  The diff IS the completeness claim (PLAN § 11.2).

   ---------- Position conventions (docs/DESIGN-NOTES.md § 1) ----------
   * A rule is stated as a pair of kernel terms at ONE position; the rule does not
     say anything about the surrounding term, so the context closure (rw_ctx /
     rw_blk below) is what the paper's `C[ ]` and `B[ ]` provide.
   * The paper's block context `B[ ] = block{∃X{hp}. □}` is written `Block X inner`,
     where `inner` is read at the block's INNER position.  Both sides of a rule then
     mention the same `Block X -` subterm, and because the quantified inner terms are
     arbitrary, the paper's freshness side conditions (`X # Y`, `Y ∉ fvs(C)`,
     `fvsol(rng(hy)) # X`) are discharged by the representation, not by a side
     condition: that is the whole point of the locally-nameless encoding, and the
     alpha rules (hp-alpha, lam-alpha) become literal identities.
   * `v ::= x | hnf` (Fig. 6 line 325): bare variables are values, so a locally-bound
     variable occurring as an expression is `Ret (VVar i)`.

   ---------- Slot bookkeeping ----------
   Slots are listed outermost-first (Syntax.v header).  For a block with `n` slots,
   the de Bruijn index of slot `p` seen from the body is `slot_body_idx n p = n-1-p`;
   seen from the value of slot `q > p` it is `q-1-p`.  `slotShiftV n p` moves a value
   written at slot `p`'s entry position to the body position; it is the map the
   `subst` rule needs (`S[x]` lives in the body, the heap entry `x v` lives at the
   slot position), and it exists for *every* value because `option Val` slots are
   already well-scoped at their own position. *)

From Stdlib Require Import ZArith Bool List.
From Timbda Require Import Syntax.
Import ListNotations.

(* ---------- index bookkeeping ---------- *)
Definition slot_body_idx (n p : nat) : nat := n - 1 - p.

(* `slotShiftV n p off v` reindexes a value whose home position is slot `p`'s entry
   position of a block with `n` slots, to the body position of that block.  `off` is
   the number of binders crossed *inside* the value (lambda binders, and the slot
   groups of nested blocks); a variable with index `i` at that depth has home index
   `i - off`, and the two home ranges (prefix slots `j < p`, outer binders `j >= p`)
   reindex by `n - p + j` and `j + n` respectively.  Home-internal binders (`i < off`)
   travel with the value and keep their indices. *)
Fixpoint slotShiftV (n p off : nat) (v : Val) : Val :=
  match v with
  | VVar i =>
      if Nat.ltb i off then VVar i
      else let j := i - off in
           if Nat.ltb j p then VVar (off + (n - p + j)) else VVar (off + (j + n))
  | VLam t e => VLam t (slotShiftE n p (S off) e)
  | VDelay e => VDelay (slotShiftE n p off e)
  | VTup vs => VTup (map (slotShiftV n p off) vs)
  | _ => v
  end
with slotShiftE (n p off : nat) (e : Expr) : Expr :=
  match e with
  | Ret v => Ret (slotShiftV n p off v)
  | Glob g => Glob g
  | App e1 e2 => App (slotShiftE n p off e1) (slotShiftE n p off e2)
  | TupE es => TupE (map (slotShiftE n p off) es)
  | Seq e1 e2 => Seq (slotShiftE n p off e1) (slotShiftE n p off e2)
  | Unify e1 e2 => Unify (slotShiftE n p off e1) (slotShiftE n p off e2)
  | Choice e1 e2 => Choice (slotShiftE n p off e1) (slotShiftE n p off e2)
  | Fail => Fail
  | Iter ic b r => Iter ic (slotShiftE n p off b) (slotShiftE n p off r)
  | Block slots body =>
      Block (walkSlotsV (fun v q => slotShiftV n p (off + q) v) 0 slots)
            (slotShiftE n p (off + length slots) body)
  end.

Definition slotValueFromBody (n p : nat) (v : Val) : Val := slotShiftV n p 0 v.

(* `slot_refs_body n p body` / slot values: does anything inside the block mention the
   binder of slot p?  Exact for the non-recursive M0 fragment: slot values at list
   position q > p see slot p at index q-1-p, and the body sees it at slot_body_idx. *)
Definition slot_unused (n p : nat) (slots : list (Ty * option Val)) (body : Expr) : bool :=
  negb (occursE (slot_body_idx n p) body) &&
  negb (anySlotsV (fun v q => if Nat.ltb p q then occursV (q - 1 - p) v else false) 0 slots).

(* Dropping slot p (GC1): slot values after p are reindexed with the `shrink` map of
   their own position (their prefix loses exactly one binder before them), the body is
   reindexed by shrinking at its own index of slot p. *)
Fixpoint removeNthGo (p i : nat) (slots : list (Ty * option Val)) : list (Ty * option Val) :=
  match slots with
  | nil => nil
  | s :: rest => if Nat.eqb i p then rest else s :: removeNthGo p (S i) rest
  end.

Definition dropSlot (n p : nat) (slots : list (Ty * option Val)) : list (Ty * option Val) :=
  removeNthGo p 0 (walkSlotsV (fun v q => if Nat.ltb p q then shrinkV (q - S p) v else v) 0 slots).

Fixpoint fillSlotGo (p : nat) (v : Val) (i : nat)
  (slots : list (Ty * option Val)) : list (Ty * option Val) :=
  match slots with
  | nil => nil
  | (t, ov) :: rest =>
      if Nat.eqb i p then (t, Some v) :: rest else (t, ov) :: fillSlotGo p v (S i) rest
  end.
Definition fillSlot (p : nat) (v : Val) (slots : list (Ty * option Val))
  : list (Ty * option Val) := fillSlotGo p v 0 slots.

Definition slot_at (slots : list (Ty * option Val)) (p : nat) : option (Ty * option Val) :=
  nth_error slots p.

(* ---------- rule-shape helpers ---------- *)
Fixpoint choice_list (es : list Expr) : Expr :=
  match es with
  | nil => Fail
  | e :: nil => e
  | e :: rest => Choice e (choice_list rest)
  end.

Definition prim_app (p : Prim) (args : list Expr) : Expr := App (Ret (VPrim p)) (TupE args).

(* EqTup1's right-hand side: v1=w1 ; ... ; vn=wn ; ⟨v1..vn⟩ (line 435).  The length
   premise makes the mixed nil/cons branch unreachable. *)
Fixpoint eq_seq (vs ws : list Val) (k : Expr) : Expr :=
  match vs, ws with
  | nil, nil => k
  | v :: vs', w :: ws' => Seq (Unify (Ret v) (Ret w)) (eq_seq vs' ws' k)
  | _, _ => k
  end.

(* beta-t candidates: for i = 0..n,  block{∃{}. x = i; v_i}   (line 469).  The inner
   `∃{}` is an empty slot list, hence index-neutral; x is the outer block's slot 0;
   v_i is a value from the application site, so it is lifted by that one binder. *)
Fixpoint beta_t_cands (i : nat) (vs : list Val) : list Expr :=
  match vs with
  | nil => nil
  | v :: rest =>
      Block nil (Seq (Unify (Ret (VVar 0)) (Ret (VInt (Z.of_nat i)))) (Ret (liftV 1 0 v)))
      :: beta_t_cands (S i) rest
  end.

(* ---------- root taxonomy (Fig. 9 note, lines 441-445; Fig. 10 note, line 463) ----------
   Function-vs-function and variable-vs-variable unification have NO rule: they are
   stuck, not fail.  Everything else with differing roots is eqfail. *)
Definition root_eqb (r1 r2 : Root) : bool :=
  match r1, r2 with
  | RInt, RInt => true
  | RBool, RBool => true
  | RUnit, RUnit => true
  | RTup, RTup => true
  | RDelay, RDelay => true
  | RPrimH, RPrimH => true
  | RLam, RLam => true
  | RootOther, RootOther => true
  | _, _ => false
  end.

Definition stuck_root (r : Root) : bool :=
  match r with RLam | RootOther => true | _ => false end.

(* Pairs with NO unification rule at all: a bare variable on either side
   (`x = x` is "stuck until x gets a value", line 444-445), or lambdas on both
   sides (lines 441-442).  Everything else with different root shapes is eqfail
   (line 437), which includes lambda-vs-literal: the note's stuck exemption is
   the *same-root* case only.  Recorded in docs/DESIGN-NOTES.md. *)
Definition no_eq_rule_pair (r1 r2 : Root) : bool :=
  match r1, r2 with
  | RootOther, _ => true
  | _, RootOther => true
  | RLam, RLam => true
  | _, _ => false
  end.

Definition root_mismatch (v1 v2 : Val) : bool :=
  let r1 := root_of v1 in
  let r2 := root_of v2 in
  negb (no_eq_rule_pair r1 r2) && negb (root_eqb r1 r2).

Definition is_int_val (v : Val) : bool := match v with VInt _ => true | _ => false end.

(* eqk1/eqk2 quantify over literals k (line 432-433; Fig. 6 line 320: unit,
   true, false, integer).  Helper for the kernel-side literal generalization. *)
Definition is_lit_val (v : Val) : bool :=
  match v with
  | VUnit | VTrue | VFalse | VInt _ => true
  | _ => false
  end.

(* ---------- slot access / body->slot reindexing (subst, promote) ----------
   `slot_value_at slots p` is the heap entry of slot p (None = declared only).
   `subV k d` decrements indices >= d by k (the inverse direction of `liftV`);
   used with d = n and k = n - p to move a value written at the *body* position
   of a block with n slots back to the entry position of slot p, under the
   precondition (the promote guard) that it references none of those n slots. *)
Definition slot_value_at (slots : list (Ty * option Val)) (p : nat) : option Val :=
  match nth_error slots p with Some (_, ov) => ov | None => @None Val end.

Fixpoint subV (k d : nat) (v : Val) : Val :=
  match v with
  | VVar i => if Nat.ltb i d then VVar i else VVar (i - k)
  | VLam t e => VLam t (subE k (S d) e)
  | VDelay e => VDelay (subE k d e)
  | VTup vs => VTup (map (subV k d) vs)
  | _ => v
  end
with subE (k d : nat) (e : Expr) : Expr :=
  match e with
  | Ret v => Ret (subV k d v)
  | Glob g => Glob g
  | App e1 e2 => App (subE k d e1) (subE k d e2)
  | TupE es => TupE (map (subE k d) es)
  | Seq e1 e2 => Seq (subE k d e1) (subE k d e2)
  | Unify e1 e2 => Unify (subE k d e1) (subE k d e2)
  | Choice e1 e2 => Choice (subE k d e1) (subE k d e2)
  | Fail => Fail
  | Iter ic b r => Iter ic (subE k d b) (subE k d r)
  | Block slots body =>
      Block (walkSlotsV (fun v q => subV k (d + q) v) d slots)
            (subE k (d + length slots) body)
  end.

Definition bodyToSlotV (n p : nat) (v : Val) : Val := subV (n - p) n v.

(* promote side condition  fvsol(v) # dom(hp) union {x}:  the value being
   unified with the unbound slot mentions no slot of its own block (all its
   free indices are outer, >= n). *)
Definition promote_ok (n : nat) (v : Val) : bool :=
  negb (existsb (fun q => occursV q v) (seq 0 n)).

(* M0 kernel-side restriction recorded in the audit: instead of the paper's
   `hp[v/x]` rewrite of *existing* heap entries, the constructor requires that
   no other valued slot currently references slot p (so the substitution is the
   identity).  The general form belongs to the admitted Tier-2 statement (M3/T1). *)
Fixpoint promoteHpGo (p i : nat) (slots : list (Ty * option Val)) : bool :=
  match slots with
  | nil => true
  | (_, Some v) :: rest =>
      (negb (Nat.ltb p i) || negb (occursV (i - 1 - p) v)) && promoteHpGo p (S i) rest
  | (_, None) :: rest => promoteHpGo p (S i) rest
  end.
Definition promote_hp_ok (slots : list (Ty * option Val)) (p : nat) : bool :=
  promoteHpGo p 0 slots.

(* =====================================================================
   `Rew lhs rhs` : a Core-Verse one-step rewrite at the root of a term.
   It is a *data* type (not a Prop) so that a rule value carries the rule
   identity into the audit tables and into the soundness lemmas
   (`RewSound_<Rule>` in Denotation.v).  Context closure lives in `rw_step` /
   `rewrites` at the end of this file.

   Tier labels follow docs/VERSE-RULES.md and classify the *statement*: Tier 2 =
   the constructor's own statement needs the evolving-heap machinery the M0
   statements omit (promote-l/r's `hp[v/x]` sub-step, float's C-general form);
   Tier 1 = everything else.  Per-ctor proof status (discharged at M0 / deferred,
   with reason class) is the table in docs/RULES-AUDIT.md section 1: tier is not
   status, and a deferred row carries no statement rather than an admitted one.
   ===================================================================== *)
Inductive Rew : Expr -> Expr -> Type :=

(* ---------- Fig. 9 (lines 432-437): unification ---------- *)
| RewEqK1 : forall v : Val,
    is_lit_val v = true ->
    Rew (Unify (Ret v) (Ret v)) (Ret v)
    (* audit: EqK1 | fig:9 | tier:1 | k = k -> k (line 432; k ranges over the
       literals unit/true/false/int — the kernel states the literal-general form,
       recorded in docs/RULES-AUDIT.md; eqtup1 handles tuples, eqfail the rest) *)
| RewEqK2 : forall v1 v2 : Val,
    is_lit_val v1 = true ->
    is_lit_val v2 = true ->
    v1 <> v2 ->
    Rew (Unify (Ret v1) (Ret v2)) Fail
    (* audit: EqK2 | fig:9 | tier:1 | k1 = k2 -> fail if k1 <> k2 (line 433) *)
| RewEqTup1 : forall vs ws : list Val,
    length vs = length ws ->
    Rew (Unify (Ret (VTup vs)) (Ret (VTup ws))) (eq_seq vs ws (Ret (VTup vs)))
    (* audit: EqTup1 | fig:9 | tier:1 | ⟨v1..vn⟩ = ⟨w1..wn⟩ -> v1=w1; .. ; vn=wn; ⟨v1..vn⟩ *)
| RewEqTup2 : forall vs ws : list Val,
    length vs <> length ws ->
    Rew (Unify (Ret (VTup vs)) (Ret (VTup ws))) Fail
    (* audit: EqTup2 | fig:9 | tier:1 | ⟨v1..vn⟩ = ⟨w1..wm⟩ -> fail if n <> m *)
| RewEqFail : forall v1 v2 : Val,
    root_mismatch v1 v2 = true ->
    Rew (Unify (Ret v1) (Ret v2)) Fail
